'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE profiles(id INTEGER PRIMARY KEY); INSERT INTO profiles VALUES(1),(2);
CREATE TABLE rss_article_hide_rules(id INTEGER PRIMARY KEY,profile_id INTEGER NOT NULL REFERENCES profiles(id) ON DELETE CASCADE, domain TEXT NOT NULL DEFAULT '', title_mode TEXT NOT NULL CHECK(title_mode IN ('all','contains','exact')), title_text TEXT NOT NULL DEFAULT '', title_text2 TEXT NOT NULL DEFAULT '', created_at INTEGER NOT NULL);
INSERT INTO rss_article_hide_rules(profile_id,domain,title_mode,title_text,title_text2,created_at) VALUES(1,'','contains','【鳴潮】',' - GameWith',111);`);
const hide=require('../app/rss-hide-rules').create({db});
assert.equal(hide.list(1).rules[0].titleOperator,'and','RC08 migration makes old two-term AND');
const source=t=>({title:t,url:'https://news.google.com/rss/articles/abc',publisherHost:'gamewith.jp'});
const title='【鳴潮】リリーの評価とおすすめパーティ編成・音骸・武器 - GameWith';
assert.equal(hide.filter(1,[source(title)]).length,0,'RC08 rule preserved');
const old=hide.list(1).rules[0];hide.remove(1,old.id);
const and=hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"【鳴潮】"+" - GameWith"'});
assert.equal(and.rules[0].titleText,'【鳴潮】');assert.equal(and.rules[0].titleText2,' - GameWith');assert.equal(and.rules[0].titleOperator,'and');
assert.equal(hide.filter(1,[source(title)]).length,0,'AND matches with Google News wrapper');
assert.equal(hide.filter(1,[source('【鳴潮】速報')]).length,1,'AND does not match first term alone');
assert.equal(hide.filter(1,[source('攻略ニュース - GameWith')]).length,1,'AND does not match second term alone');
hide.remove(1,and.id);
const or=hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"【鳴潮】"or" - GameWith"'});
assert.equal(or.rules[0].titleOperator,'or');
assert.equal(hide.filter(1,[source('【鳴潮】速報')]).length,0,'OR first term');
assert.equal(hide.filter(1,[source('攻略ニュース - GameWith')]).length,0,'OR second term');
assert.equal(hide.filter(1,[source('関係ない記事')]).length,1,'OR unrelated title');
assert.equal(hide.filter(2,[source(title)]).length,1,'profile isolated');
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"+"B"or"C"'}),/半角ダブルクォート/);
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"+'}),/半角ダブルクォート/);
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"or"B"or"C"'}),/半角ダブルクォート/);
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"+"A"'}),/2つの語句/);
const dup=hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"or"B"'});
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"or"B"'}),/同じルール/);hide.remove(1,dup.id);
const exact=hide.add(1,{domain:'',titleMode:'exact',titleExpression:'A or B'});
assert.equal(hide.filter(1,[source('A or B')]).length,0,'exact uses expression literally');
assert.equal(hide.filter(1,[source('A')]).length,1,'exact does not parse operator');
const literal=hide.add(1,{domain:'',titleMode:'contains',titleExpression:'C++'});
assert.equal(hide.filter(1,[source('Learn C++')]).length,0,'literal plus without separated spaces');
hide.remove(1,or.id);hide.remove(1,exact.id);hide.remove(1,literal.id);
assert.equal(hide.filter(1,[source(title)]).length,1,'remove restores immediately');
const fs=require('node:fs'); const ui=fs.readFileSync(require('node:path').join(__dirname,'../app/public/app.js'),'utf8');
assert.ok(ui.includes('半角ダブルクォートで指定'));
assert.ok(ui.includes('JSON.stringify(r.titleText2)'),'saved rules visually show both exact phrases');
assert.ok(!ui.includes('追加の語句（任意・両方含む場合だけ非表示）'));
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'A + B'}),/半角ダブルクォート/);
assert.throws(()=>hide.add(1,{domain:'',titleMode:'contains',titleExpression:'"A"orB'}),/半角ダブルクォート/);
console.log('PASS: quoted single-field title expressions, AND/OR, migration, legacy, GUI');
